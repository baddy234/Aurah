fun getAppStrings(language: String): AppStrings {
    return when {
        language.contains("UK", ignoreCase = true) -> EnglishUKStrings
        language.contains("Español", ignoreCase = true) || language.contains("Spanish", ignoreCase = true) -> SpanishStrings
        language.contains("Français", ignoreCase = true) || language.contains("French", ignoreCase = true) -> FrenchStrings
        language.contains("Deutsch", ignoreCase = true) || language.contains("German", ignoreCase = true) -> GermanStrings
        language.contains("日本語", ignoreCase = true) || language.contains("Japanese", ignoreCase = true) -> JapaneseStrings
        language.contains("中文", ignoreCase = true) || language.contains("Chinese", ignoreCase = true) -> ChineseStrings
        language.contains("Português", ignoreCase = true) || language.contains("Portuguese", ignoreCase = true) -> PortugueseStrings
        language.contains("Italiano", ignoreCase = true) || language.contains("Italian", ignoreCase = true) -> ItalianStrings
        language.contains("한국어", ignoreCase = true) || language.contains("Korean", ignoreCase = true) -> KoreanStrings
        else -> EnglishUSStrings
    }
}

fun getLocaleForLanguage(language: String): Locale {
    return when {
        language.contains("UK", ignoreCase = true) -> Locale.UK
        language.contains("Español", ignoreCase = true) || language.contains("Spanish", ignoreCase = true) -> Locale("es", "ES")
        language.contains("Français", ignoreCase = true) || language.contains("French", ignoreCase = true) -> Locale.FRANCE
        language.contains("Deutsch", ignoreCase = true) || language.contains("German", ignoreCase = true) -> Locale.GERMANY
        language.contains("日本語", ignoreCase = true) || language.contains("Japanese", ignoreCase = true) -> Locale.JAPAN
        language.contains("中文", ignoreCase = true) || language.contains("Chinese", ignoreCase = true) -> Locale.SIMPLIFIED_CHINESE
        language.contains("Português", ignoreCase = true) || language.contains("Portuguese", ignoreCase = true) -> Locale("pt", "BR")
        language.contains("Italiano", ignoreCase = true) || language.contains("Italian", ignoreCase = true) -> Locale.ITALY
        language.contains("한국어", ignoreCase = true) || language.contains("Korean", ignoreCase = true) -> Locale.KOREA
        else -> Locale.US
    }
}

